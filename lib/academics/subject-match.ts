import { normalizeForMatch } from "@/lib/ai/lecture-intensive";

/**
 * مطابقة اسم مادة بآخر — مسامحة بعد التطبيع.
 * الفرق عن المساواة المباشرة: الاشتراك الجزئي بشرط طول كافٍ (3+) عشان
 * «ف» ما تطابقش كل حاجة.
 */
export function subjectMatches(a: string, b: string): boolean {
  const x = normalizeForMatch(a);
  const y = normalizeForMatch(b);
  if (!x || !y) return false;
  if (x === y) return true;
  return x.length >= 3 && y.length >= 3 && (x.includes(y) || y.includes(x));
}
