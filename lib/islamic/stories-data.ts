/** فلترة القصص بالفئة (أو كل القصص). */
export function filterStoriesByCategory(category: StoryCategory | "all"): Story[] {
  if (category === "all") return STORIES;
  return STORIES.filter((story) => story.category === category);
}

/** إحصاءات الفئات (لشبكة الكروت). */
export function getStoryCategoryCounts(): Record<StoryCategory, number> {
  const counts: Record<StoryCategory, number> = {
    sahabi: 0,
    sahabiyya: 0,
    tabii: 0,
    tabiiyya: 0,
  };
  for (const story of STORIES) {
    counts[story.category] += 1;
  }
  return counts;
}

/** البحث عن قصة بالمعرّف. */
export function getStoryById(id: string): Story | undefined {
  return STORIES.find((story) => story.id === id);
}

/** البحث في القصص (العنوان/الشخصية/النص/الدرس) مع فلترة اختيارية بالفئة. */
export function searchStories(
  query: string,
  category: StoryCategory | "all" = "all",
): Story[] {
  const normalizedQuery = normalizeArabicText(query);
  const pool = filterStoriesByCategory(category);
  if (!normalizedQuery) return pool;
  return pool.filter((story) => {
    const haystack = normalizeArabicText(
      [story.title, story.person, story.role, ...story.paragraphs, story.lesson].join(" "),
    );
    return haystack.includes(normalizedQuery);
  });
}

/** إزالة التشكيل وتوحيد الحروف لتوحيد البحث العربي. */
function normalizeArabicText(input: string): string {
  return input
    .replace(/[\u064B-\u0652\u0670\u0640\u06D6-\u06ED]/g, "")
    .replace(/[\u0623\u0625\u0622]/g, "\u0627")
    .replace(/\u0649/g, "\u064A")
    .replace(/\u0629/g, "\u0647")
    .replace(/\s+/g, " ")
    .trim();
}
