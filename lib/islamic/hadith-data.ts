/** كتب السنة المعتمدة هنا (الصحيحان فقط لأمان الداتا). */
export type HadithCollection = "bukhari" | "muslim";

/** تصنيفات الأحاديث المعتمدة في الصفحة. */
export type HadithCategory = "iman" | "akhlaq" | "ilm" | "adhkar" | "sadaqah";

/** الحديث الواحد كما يُعرض في الصفحة. */
export interface Hadith {
  /** مُعرّف فريد: collection-number. */
  id: string;
  /** تصنيف الحديث. */
  category: HadithCategory;
  /** النص الكامل (إسناد ومتن) كما ورد حرفياً في النسخة الموثّقة. */
  text: string;
  /** الصحابي الراوي. */
  narrator: string;
  /** الكتاب. */
  collection: HadithCollection;
  /** رقم الحديث في الكتاب (ترقيم sunnah.com). */
  hadithNumber: number;
  /** اسم المصدر مع الرقم (مثل: صحيح البخاري 1). */
  source: string;
  /** رابط المصدر للتحقق. */
  sourceUrl: string;
}

/** مرجع حديث إضافي يُجاب ديناميكياً من الـ API عبر البروكسي. */
export interface HadithRef {
  collection: HadithCollection;
  hadithNumber: number;
  narrator: string;
  category: HadithCategory;
}

