/**
 * حديث اليوم — ثابت خلال اليوم بالتاريخ (لا يتغير مع كل ريندر):
 * يُشتق من عدد الأيام المحلية منذ البداية، فكل يوم يظهر حديث مختلف بثبات.
 */
export function getHadithOfTheDay(now: Date = new Date()): Hadith {
  const dayIndex = Math.floor(
    Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) / 86_400_000,
  );
  const index = ((dayIndex % HADITHS.length) + HADITHS.length) % HADITHS.length;
  return HADITHS[index];
}

/** البحث النصي في الأحاديث (في المتن/الراوي/المصدر) مع فلترة اختيارية بالتصنيف. */
export function searchHadiths(
  query: string,
  category: HadithCategory | "all" = "all",
): Hadith[] {
  const normalizedQuery = normalizeArabicText(query);
  return HADITHS.filter((hadith) => {
    if (category !== "all" && hadith.category !== category) return false;
    if (!normalizedQuery) return true;
    const haystack = normalizeArabicText(
      `${hadith.text} ${hadith.narrator} ${hadith.source}`,
    );
    return haystack.includes(normalizedQuery);
  });
}

/** تقسيم الأحاديث الثابتة على التصنيفات (لشبكة كروت التصنيفات). */
export function groupHadithsByCategory(): Record<HadithCategory, Hadith[]> {
  const grouped: Record<HadithCategory, Hadith[]> = {
    iman: [],
    akhlaq: [],
    ilm: [],
    adhkar: [],
    sadaqah: [],
  };
  for (const hadith of HADITHS) {
    grouped[hadith.category].push(hadith);
  }
  return grouped;
}
