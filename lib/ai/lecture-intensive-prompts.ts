/**
 * يبني رسالة المستخدم لقطعة واحدة.
 *
 * ⚠️ **ليه نبعّد التوقيت عن الموديل**: الموديل بيحتاج الرقم بس.
 *   التوقيت بيتحسب عندنا من `segments[seg].start`. من غير ده
 *   الموديل ممكن يدّعي وقت غلط، وإحنا مش هنعرف نشوف.
 */
export function buildIntensiveMessages(input: {
  chunk: TimedSegment[];
  chunkIndex: number;
  chunkCount: number;
}): AiChatMessage[] {
  const { chunk, chunkIndex, chunkCount } = input;

  const lines = chunk.map(
    (segment) => `[S${segment.index}] ${segment.text}`,
  );

  const header =
    chunkCount > 1
      ? `هذا الجزء ${chunkIndex + 1} من ${chunkCount} من محاضرة طويلة.`
      : "هذا تفريغ محاضرة.";

  const user = [
    header,
    "---",
    "كل سطر بالشكل ده: رقم المقطع (S<رقم>) ثم النص.",
    "استخدم الأرقام دي بالظبط في `seg`.",
    "",
    ...lines,
  ].join("\n");

  return [
    { role: "system", content: INTENSIVE_SYSTEM },
    { role: "user", content: user },
  ];
}
