/** مقطع واحد بتوقيته — الوحدة اللي بتتقسّم بيها المحاضرة. */
export type TimedSegment = {
  /** الفهرس العام للمقطع في المحاضرة (0-based) — ده الـ anchor. */
  index: number;
  /** بداية المقطع بالثواني. */
  start: number;
  /** نهاية المقطع بالثواني. */
  end: number;
  /** نص المقطع. */
  text: string;
};

