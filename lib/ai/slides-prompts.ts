/**
 * يبني رسالة المستخدم لجزء من الصفحات.
 *
 * @param pages الوحدات (صفحات/شرائح/فقرات) — كل واحدة رقمها ونصّها.
 */
export function buildSlidesMessages(input: {
  pages: Array<{ number: number; text: string }>;
  partIndex: number;
  totalParts: number;
  unitLabel: string;
}): AiChatMessage[] {
  const { pages, partIndex, totalParts, unitLabel } = input;

  const body = pages
    .map((page) => `[P${page.number}] ${page.text}`)
    .join("\n\n");

  const header =
    totalParts > 1
      ? `الجزء ${partIndex + 1} من ${totalParts} من المحاضرة (${unitLabel}).`
      : `الجزء ده من المحاضرة (${unitLabel}).`;

  const user = [
    header,
    "",
    "كل سطر بالشكل ده: رقم الصفحة (P<رقم>) ثم نص الصفحة.",
    "استخدم الأرقام دي بالظبط في `page`.",
    "",
    body,
  ].join("\n");

  return [
    { role: "system", content: SLIDES_SYSTEM },
    { role: "user", content: user },
  ];
}
