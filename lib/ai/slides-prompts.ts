/**
 * يبني رسالة المستخدم لجزء من الصفحات.
 *
 * @param pages الوحدات (صفحات/شرائح/فقرات/مقاطع) — كل واحدة رقمها ونصّها.
 * @param sourceKind نوع المصدر — بيغيّر تعليمات تنظيف الـ ASR.
 */
export function buildSlidesMessages(input: {
  pages: Array<{ number: number; text: string; label?: string }>;
  partIndex: number;
  totalParts: number;
  unitLabel: string;
  /** افتراضي `document` (نص مكتوب) — المحاضرة بتبعت `transcript`. */
  sourceKind?: SlidesSourceKind;
  /**
   * ⭐ **عدد الشرائح المستهدف** للجزء ده.
   *
   * ⚠️ **ليه محتاجينه؟**: من غير هدف، الموديل بيعمل **شريحة لكل فكرة**
   *    ⇒ شريحة بنقطة واحدة (رفيعة) أو ٦ شرائح لنص صغير. الهدف بيخليه
   *    يجمّع الأفكار.
   */
  slidesTarget?: number;
}): AiChatMessage[] {
  const { pages, partIndex, totalParts, unitLabel } = input;
  const sourceKind = input.sourceKind ?? "document";
  const slidesTarget = Math.max(1, Math.min(6, input.slidesTarget ?? 3));

  // ⚠️ **اسم الوحدة مع «ال»** — «الصفحة» / «المقطع» / «الشريحة».
  const unitNoun = `ال${unitLabel}`;

  const body = pages
    .map((page) => `[P${page.number}] ${page.text}`)
    .join("\n\n");

  const header =
    totalParts > 1
      ? `الجزء ${partIndex + 1} من ${totalParts} من المحاضرة (${unitLabel}).`
      : `الجزء ده من المحاضرة (${unitLabel}).`;

  // ⚠️ **تنبيه المصدر** — الموديل لازم يعرف ده تفريغ ولا مستند.
  const sourceHint =
    sourceKind === "transcript"
      ? "⚠️ الكلام ده **تفريغ صوتي** — فيه أخطاء التفريغ وكلام محكي. صحّح ووضّح وانسى الحشو."
      : "المحتوى ده من **مستند مكتوب**.";

  const user = [
    header,
    "",
    sourceHint,
    "",
    `كل سطر بالشكل ده: رقم ${unitNoun} (P<رقم>) ثم نص ${unitNoun}.`,
    "استخدم الأرقام دي بالظبط في `page`.",
    "",
    body,
  ].join("\n");

  return [
    { role: "system", content: buildSlidesSystem(unitNoun, sourceKind, slidesTarget) },
    { role: "user", content: user },
  ];
}
