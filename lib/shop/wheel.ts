/**
 * عجلة الحظ — لفة واحدة في اليوم.
 *
 * ⚠️⚠️ **العجلة مكافأة مذاكرة، مش مكافأة دخول.** `spin_wheel` في
 * db/shop.sql بترفض اللفة لو مفيش في السجل النهارده كسب من `day_done` أو
 * `goal_done`. القيد ده هو اللي بيخلّي العجلة متكسرش قاعدة المشروع
 * «الكوينز بالمذاكرة بس» — عجلة بتلف بمجرد ما تفتح الموقع بتبقى مصدر
 * دخل من غير مذاكرة، وده بالظبط اللي إحنا بنمنعه.
 *
 * ⚠️ الجوايز هنا **للعرض بس** (رسم العجلة والليبل). السحب الحقيقي في
 * `shop_wheel_prizes` في الداتابيز، ومجموع أوزانه هو اللي بيحكم. الملف ده
 * بيتولّد منه صفوف السييد فالاتنين بيفضلوا متطابقين — بس لو حد عدّل هنا
 * ونسي يشغّل السكريبت، **الداتابيز هي اللي بتفوز**.
 *
 * ── سقف اليوم ──
 * أعلى جايزة ١٢٠ كوين واحتمالها ١٪. القيمة المتوقعة ~٢٨ كوين في اليوم،
 * يعني أقل من متوسط الكسب من يوم مذاكرة واحد (`day_done` = ٢٥ × سقف ٣).
 * ده مقصود: العجلة توابل على المذاكرة مش بديل عنها.
 */

export type WheelPrize = {
  id: string;
  /** بيبان في الشريحة وفي رسالة النتيجة */
  label: string;
  coins: number;
  /** من ١٠٠٠٠ — نفس مقياس أوزان الصناديق */
  weight: number;
  /**
   * عيلة لون الشريحة. الواجهة بتبني منها `--hl-{hl}-fill` و`--hl-{hl}-ink`،
   * فالقيمة **لازم** تكون عيلة موجودة بالاتنين في globals.css:
   * `yellow` `green` `red` `blue` `purple` `indigo`.
   *
   * ⚠️ مش أي اسم لون. `orange` مثلاً عنده `ink` بس من غير `fill`، وأسماء
   * زي `slate` أو `amber` مش موجودة أصلاً — والنتيجة شريحة بلا لون بتفضل
   * ساكتة (CSS بيتخطّى المتغير الناقص من غير خطأ). عشان كده الاختيار
   * محصور في الليستة اللي فوق.
   */
  hl: "yellow" | "green" | "red" | "blue" | "purple" | "indigo";
};

/**
 * تمان شرايح. عدد زوجي عشان العجلة تبان متوازنة، وترتيبها بيلفّ بين
 * الصغير والكبير فمفيش نص عجلة كله جوايز كبيرة (شكل بيحسّس إن اللفة
 * «قربت» — وده تلاعب بصري).
 */
export const WHEEL_PRIZES: readonly WheelPrize[] = [
  { id: "w.5", label: "٥ كوين", coins: 5, weight: 2400, hl: "green" },
  { id: "w.40", label: "٤٠ كوين", coins: 40, weight: 900, hl: "purple" },
  { id: "w.10", label: "١٠ كوين", coins: 10, weight: 2200, hl: "green" },
  { id: "w.60", label: "٦٠ كوين", coins: 60, weight: 400, hl: "yellow" },
  { id: "w.15", label: "١٥ كوين", coins: 15, weight: 1800, hl: "blue" },
  { id: "w.120", label: "١٢٠ كوين", coins: 120, weight: 100, hl: "red" },
  { id: "w.20", label: "٢٠ كوين", coins: 20, weight: 1400, hl: "blue" },
  { id: "w.30", label: "٣٠ كوين", coins: 30, weight: 800, hl: "purple" },
];

/* --------------------------------------------------------------------------
   فحوص التوازن — بتتنادى في سكربت السييد
   -------------------------------------------------------------------------- */

/** مجموع الأوزان = ١٠٠٠٠ بالظبط */
export function wheelOddsSane(): boolean {
  return WHEEL_PRIZES.reduce((t, p) => t + p.weight, 0) === 10000;
}

/** القيمة المتوقعة للفة الواحدة بالكوينز */
export function wheelExpected(): number {
  return WHEEL_PRIZES.reduce((t, p) => t + (p.weight / 10000) * p.coins, 0);
}

/**
 * أعلى جايزة لازم تفضل أقل من أرخص صندوق (٢٦٠) — يعني لفة واحدة عمرها
 * ما تجيب صندوق. من غير القيد ده العجلة تبقى الطريق الأسرع للصناديق،
 * والصناديق مفروض تتجاب بالمذاكرة.
 */
export function wheelCapSafe(cheapestBox: number): boolean {
  return Math.max(...WHEEL_PRIZES.map((p) => p.coins)) < cheapestBox;
}
