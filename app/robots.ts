/* ==========================================================================
   🤖 robots.txt — بتتولّد على /robots.txt

   ═══ فرق مهم: Disallow مش noindex ═══
   الملف ده بيمنع **الزحف**، والميتاداتا بتمنع **الفهرسة**. الاتنين مش
   نفس الحاجة: صفحة متمنوعة من الزحف ممكن برضه تظهر في النتايج لو حد
   لينكها من بره (جوجل بيعرض اللينك من غير عنوان ولا وصف).
   عشان كده الصفحات الخاصة عندها **الاتنين**: `Disallow` هنا +
   `noIndex` في `pageMeta()`.

   ⚠️ وفي حالة واحدة الاتنين مايتحطوش مع بعض: لو منعت الزحف على صفحة،
   جوجل **مش هيقدر يقرا** الـ noindex اللي جواها. الترتيب الصح للصفحات
   اللي عايزها تتشال من النتايج نهائياً: سيبها تتزحف بالـ noindex الأول،
   ولما تختفي من النتايج ساعتها امنع الزحف. اللي تحت كله صفحات ورا
   تسجيل دخول (الزاحف أصلاً مابيشوف غير شاشة الدخول) فمفيش تعارض.
   ========================================================================== */

import type { MetadataRoute } from 'next';
import { SITE_URL } from '@/lib/seo';

export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: '*',
        allow: '/',
        disallow: [
          /* راوتس الـ API: مفيش فيها محتوى للقراءة، وبعضها بيكلّف فلوس
             على Groq/OCR لو حد زحف عليها. */
          '/api/',

          /* محتوى شخصي ورا تسجيل دخول — مالوش أي قيمة في نتايج البحث */
          '/dashboard/',
          '/lesson/',
          '/assessment',

          /* صفحات إجراء مش محتوى. `/auth/callback` بالذات بياخد توكنات
             في الـ query string — ماينفعش تتفهرس أبداً. */
          '/login',
          '/auth/',

          /* ملفات داخلية بتاعة Next — مالهاش لازمة في الزحف */
          '/_next/',
        ],
      },
    ],
    sitemap: `${SITE_URL}/sitemap.xml`,
    host: SITE_URL,
  };
}
