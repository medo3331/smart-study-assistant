'use client';

import Link from 'next/link';
import { useLanguage } from '@/lib/i18n/LanguageProvider';

/* ==========================================================================
   🪄 شعار ماجيكلي — المصدر الوحيد للعلامة والاسم.

   كان الشعار مكتوب بإيده في ٥ حتت (٤ نافبار + الفوتر) بنفس السبانين
   بالظبط. أي تغيير في البراند كان لازم يتعمل ٥ مرات، ونسيان واحدة
   مابيكسرش أي حاجة — بيسيب صفحة واحدة بالاسم القديم وخلاص. عشان كده
   بقى مكوّن.
   ========================================================================== */

/**
 * العلامة نفسها: ضربة قلم واحدة على شكل M + نجمة رباعية.
 *
 * ═══ ليه inline SVG مش <Image src="/logo-mono.svg"> ═══
 * `currentColor`. الـ `<img>` بيرندر الـ SVG في مستند منفصل مالوش أي علم
 * بلون العنصر اللي حاطط فيه، فالعلامة كانت هتتقفل على لون واحد وتفضل
 * كده في الـ ١٥ باليتة والثيمين. جوّه المستند بترث اللون من `color`.
 * وكمان: مفيش ريكويست تاني ومفيش لحظة الأيقونة فيها لسه مش نازلة.
 *
 * ⚠️ الإحداثيات مقيسة من لوح اللوجو الأصلي، ومتطابقة حرف بحرف مع
 * `app/icon.svg` و `public/logo-mark.svg` و مولّد صورة الـ OG. لو اتغيرت
 * هنا لازم تتغير هناك — من غير كده الفافيكون والشير كارد يبقوا لوجو تاني.
 */
export function BrandGlyph({ className }: { className?: string }) {
  return (
    <svg className={className} viewBox="0 0 56.87 45" aria-hidden="true">
      <path
        d="M4.15 40.8L4.15 5.8L23.67 22.55L39.47 5.6"
        fill="none"
        stroke="currentColor"
        strokeWidth="8.3"
        strokeLinecap="round"
        strokeLinejoin="round"
      />
      <path
        d="M48.17 0Q48.17 8.65 56.87 8.65Q48.17 8.65 48.17 17.3Q48.17 8.65 39.47 8.65Q48.17 8.65 48.17 0Z"
        fill="currentColor"
      />
    </svg>
  );
}

/**
 * لوكاب النافبار: العلامة + «ماجيكلي» + «للمذاكرة بسحر».
 *
 * الاسم بقى كلمة واحدة، فالتقسيمة القديمة (نصّه حبر ونصّه معلّم فسفوري)
 * مابقالهاش معنى — «ماجي/كلي» مش تقسيمة، دي كلمة مقطوعة. السطر الوصفي
 * بياخد الأكسنت بدالها.
 *
 * ⚠️ والسطر الوصفي **نص ملوّن مش ضربة `.mark`**: الهيرو تحته بشعرة فيه
 * ضربة فسفورية على كلمة «بسحر» — نفس الكلمة. ضربتين على نفس الكلمة على
 * بعد سنتيمترات هي بالظبط الحاجة اللي التصميم اتصلّح منها قبل كده.
 * الشاشة الواحدة فيها ضربة واحدة، وهي بتروح للهيرو.
 */
export function BrandLock() {
  const { t } = useLanguage();

  return (
    <Link href="/" className="brand">
      <BrandGlyph className="brand-glyph" />
      <span className="brand-text">
        <span className="brand-name">{t.brand}</span>
        <span className="brand-tagline">{t.brand_tagline}</span>
      </span>
    </Link>
  );
}
