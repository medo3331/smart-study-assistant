/* ==========================================================================
   🧩 وسم البيانات المنظّمة — مكوّن واحد بدل ما كل صفحة تكرّر نفس السطور.

   ⚠️ الـ `.replace(/</g, '\\u003c')` **مش تزويقة**. من غيره أي نص فيه
   `</script>` (سؤال في الأسئلة الشائعة، اسم مادة، أي حاجة جاية من داتا)
   بيقفل الوسم بدري والباقي بيتنفّذ كـ HTML — دي ثغرة XSS كلاسيكية.
   الهروب بيخلي المتصفح يقرا الحرف كنص جوّه الـ JSON من غير ما يشوفه
   كبداية وسم. مايتشالش.

   `<script>` عادي مش `next/script`: ده بيانات بتتقري، مش كود بيتنفّذ —
   وده اللي التوثيق بتاع Next نفسه بيوصّي بيه للـ JSON-LD.
   ========================================================================== */

export function JsonLd({ data }: { data: object | object[] }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(data).replace(/</g, '\\u003c'),
      }}
    />
  );
}
